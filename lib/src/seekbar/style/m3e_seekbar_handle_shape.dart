/// The shape token for the handle (thumb) of [M3ESeekbar] and [M3EWavySeekbar].
enum M3ESeekbarHandleShape {
  /// A circular handle, traditional for media seekbars.
  circle,

  /// A vertical rectangular / pill handle with rounded corners, following
  /// Material 3 Expressive slider handle styling.
  rectangle,
}
